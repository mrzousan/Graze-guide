// Downloads every plant photo once, stores it in app/assets/plants/, and writes app/src/data/images.ts
// so the photos ship inside the app (they work offline).
// Run from the app folder:  node ../tools/fetch-images.mjs      (needs Node 18 or newer)
// It is safe to run again: files already downloaded are skipped, and it can be stopped and resumed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const photos = JSON.parse(fs.readFileSync(path.join(here, 'photos.json'), 'utf8'));
const outDir = path.join(here, '..', 'app', 'assets', 'plants');
const mapFile = path.join(here, '..', 'app', 'src', 'data', 'images.ts');
fs.mkdirSync(outDir, { recursive: true });

// Wikimedia asks automated clients to identify themselves and go slowly.
const UA = 'GrazeGuideApp/1.0 (grazeguide.app@gmail.com) fetch-images script';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const jobs = [];
for (const [id, list] of Object.entries(photos)) list.forEach((p, i) => jobs.push({ file: `${id}-${i + 1}.jpg`, url: p.url.replace('width=800', 'width=600') }));

let done = 0, failed = [];
for (const j of jobs) {
  const dest = path.join(outDir, j.file);
  if (fs.existsSync(dest) && fs.statSync(dest).size > 2000) { done++; continue; }
  let ok = false;
  for (let attempt = 1; attempt <= 4 && !ok; attempt++) {
    try {
      const res = await fetch(j.url, { headers: { 'User-Agent': UA }, redirect: 'follow' });
      if (res.status === 429 || res.status >= 500) { await sleep(3000 * attempt); continue; }
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const type = res.headers.get('content-type') || '';
      if (!type.startsWith('image/')) throw new Error('not an image: ' + type);
      fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
      ok = true;
    } catch (e) { if (attempt === 4) failed.push(`${j.file}: ${e.message}`); else await sleep(1500 * attempt); }
  }
  done++;
  if (done % 25 === 0) console.log(`${done}/${jobs.length}`);
  await sleep(400);
}

const have = jobs.filter((j) => fs.existsSync(path.join(outDir, j.file)) && fs.statSync(path.join(outDir, j.file)).size > 2000);
const lines = have.map((j) => `  ${JSON.stringify(j.file)}: require('../../assets/plants/${j.file}'),`);
fs.writeFileSync(mapFile, `// Generated by tools/fetch-images.mjs. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';

export const IMAGES: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};
`);
console.log(`Done. ${have.length} of ${jobs.length} photos saved.`);
if (failed.length) { console.log('These failed (run the script again to retry):'); failed.forEach((f) => console.log('  ' + f)); }
